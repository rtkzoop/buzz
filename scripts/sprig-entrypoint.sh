#!/bin/bash
set -euo pipefail

# Match desktop's URL-scoped git credential configuration without installing a
# helper globally (which would make it answer for unrelated remotes).
if [[ -n "${BUZZ_RELAY_URL:-}" ]]; then
    relay_http_url="${BUZZ_RELAY_URL/#ws:/http:}"
    relay_http_url="${relay_http_url/#wss:/https:}"
    relay_http_url="${relay_http_url%/}"
    git config --global "credential.${relay_http_url}/git.helper" \
        /usr/local/bin/git-credential-nostr
    git config --global "credential.${relay_http_url}/git.useHttpPath" true
fi

# Point the Grok CLI at an OpenAI-compatible proxy (e.g. CLIProxyAPI) instead of
# xAI directly. Only runs when the operator opts in via GROK_PROXY_BASE_URL.
#
# Both endpoints must be redirected, not just one: after Grok selects api-key
# auth it sends completions to the *xAI API* base URL, so overriding only
# `cli_chat_proxy_base_url` still reaches api.x.ai and fails with "Incorrect API
# key provided".
#
# XAI_API_KEY must also be non-empty, even when the proxy ignores its value:
# without it Grok never advertises the `xai.api_key` auth method and refuses
# `session/new` with "Authentication required" before issuing any request. We
# default it to a placeholder rather than failing, since proxies that terminate
# auth upstream have no real key to give.
#
# Written only when absent, so a config baked into the image or mounted over
# /home/agent still wins.
if [[ -n "${GROK_PROXY_BASE_URL:-}" ]]; then
    grok_home="${HOME:-/home/agent}/.grok"
    grok_config="${grok_home}/config.toml"
    if [[ ! -e "$grok_config" ]]; then
        mkdir -p "$grok_home"
        grok_model="${GROK_PROXY_MODEL:-grok-4.5}"
        cat > "$grok_config" <<EOF
# Generated by sprig-entrypoint from GROK_PROXY_BASE_URL. Edit the environment,
# not this file: it is only written when no config.toml already exists.
[models]
default = "${grok_model}"

[endpoints]
xai_api_base_url = "${GROK_PROXY_BASE_URL}"
cli_chat_proxy_base_url = "${GROK_PROXY_BASE_URL}"

[model."${grok_model}"]
base_url = "${GROK_PROXY_BASE_URL}"
env_key = "XAI_API_KEY"
EOF
    fi
    export XAI_API_KEY="${XAI_API_KEY:-proxy-managed}"
fi

# The harness must receive Kubernetes' termination signal directly.
exec buzz-acp "$@"
